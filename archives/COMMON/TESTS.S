(define (tester)
  (let ((n 0))
    (for-each (lambda (x)
                (let ((result (reduce (car x))))
                  (set! n (1+ n))
                  (if (lac-equal? (compile-exp result) (compile-exp (cdr x)))
                      (writeln 'test " " n " " 'ok)
                      (writeln 'test " " n " " 'error))))
              tests)))
  
(define (lac-equal? a b)
  (cond ((and (null? a) (null? b)) #T)
        ((or (null? a) (null? b)) #F)
        ((and (eq? (cadar a) 'NAMED) (eq? (cadar b) 'NAMED))
         (lac-equal? (cdr a) (cdr b)))
        ((equal? (car a) (car b))
         (lac-equal? (cdr a) (cdr b)))))
